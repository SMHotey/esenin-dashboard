// «Сегодня» для сайта считаем по Москве, а не по UTC.
//
// Причина: даты журнала — редакционные, их ставит человек в московском
// календаре, а даты в data/updated.json берутся из git-коммитов, то есть
// из локального времени автора. CI живёт в UTC, который отстаёт от Москвы
// на три часа: с 00:00 до 03:00 МСК там ещё вчера. Без этой поправки
// публикация на сегодня в такой час считается будущей (и не попадает
// в сборку), а свежие даты «Обновлено» — датами из будущего (verify падает).
export function moscowToday(now = new Date()) {
  return new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Europe/Moscow',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(now);
}
